#!/usr/bin/env python3
"""Generates the Blivzy AI logo (C header), app icon and preview images.
Run from anywhere:  python3 tools/make_assets.py   (needs Pillow)"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "app", "blivzy_ai")
DOCS = os.path.join(ROOT, "docs")

G = {
 "B": ["11110","10001","10001","11110","10001","10001","11110"],
 "L": ["10000","10000","10000","10000","10000","10000","11111"],
 "I": ["11111","00100","00100","00100","00100","00100","11111"],
 "V": ["10001","10001","10001","10001","10001","01010","00100"],
 "Z": ["11111","00001","00010","00100","01000","10000","11111"],
 "Y": ["10001","10001","01010","00100","00100","00100","00100"],
 "A": ["01110","10001","10001","11111","10001","10001","10001"],
}

def blocks(d, text, x, y, s, ink=0):
    for ch in text:
        for r, row in enumerate(G[ch]):
            for c, v in enumerate(row):
                if v == "1":
                    d.rectangle([x+c*s, y+r*s, x+c*s+s-1, y+r*s+s-1], fill=ink)
        x += 6 * s

def logo():
    im = Image.new("L", (128, 64), 255)
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, 127, 63], radius=5, outline=0)
    d.rounded_rectangle([3, 3, 124, 60], radius=3, outline=0)
    blocks(d, "BLIVZY", 11, 8, 3)
    d.line([11, 34, 116, 34], fill=0)
    d.polygon([(64, 31), (67, 34), (64, 37), (61, 34)], fill=0)
    blocks(d, "AI", 53, 38, 2)
    for x0, x1 in ((11, 45), (83, 116)):
        d.line([x0, 44, x1, 44], fill=0)
    for x in (11, 116):
        d.rectangle([x-1, 43, x+1, 45], fill=0)
    return im

def write_header(im):
    out = []
    for y in range(64):
        for xb in range(16):
            b = 0
            for i in range(8):
                if im.getpixel((xb*8+i, y)) < 128:
                    b |= 1 << i
            out.append(b)
    lines = []
    for i in range(0, len(out), 16):
        lines.append("    " + ", ".join("0x%02x" % v for v in out[i:i+16]) + ",")
    with open(os.path.join(APP, "blivzy_logo.h"), "w") as f:
        f.write("// Generated by tools/make_assets.py - 128x64 XBM splash logo\n#pragma once\n#include <stdint.h>\n\n")
        f.write("static const uint8_t blivzy_logo[] = {\n" + "\n".join(lines) + "\n};\n")

def icon():
    im = Image.new("1", (10, 10), 1)
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, 9, 9], fill=0)
    for r, row in enumerate(G["B"]):
        for c, v in enumerate(row):
            if v == "1":
                im.putpixel((2+c, 1+r), 1) if 2+c < 10 and 1+r < 10 else None
    im.save(os.path.join(APP, "icon.png"))

def font():
    try:
        return ImageFont.load_default(size=8)
    except TypeError:
        return ImageFont.load_default()

def mono(im):
    return im.convert("1", dither=Image.NONE)

def new_screen():
    im = Image.new("1", (128, 64), 1)
    return im, ImageDraw.Draw(im), font()

def wrap(d, text, f, width=122):
    lines = []
    for para in text.split("\n"):
        cur = ""
        for word in para.split(" "):
            t = (cur + " " + word).strip() if cur else word
            if d.textlength(t, font=f) <= width:
                cur = t
            else:
                lines.append(cur)
                cur = word
        lines.append(cur)
    return lines

def screen_text(text, scroll=True):
    im, d, f = new_screen()
    for i, ln in enumerate(wrap(d, text, f)[:7]):
        d.text((2, 1 + i * 9), ln, font=f, fill=0)
    if scroll:
        d.rectangle([125, 0, 126, 38], fill=0)
    return im

def screen_splash():
    im = logo().convert("1", dither=Image.NONE)
    d = ImageDraw.Draw(im)
    f = font()
    t = "Made by Blivzy  v0.4"
    w = d.textlength(t, font=f)
    d.text(((128 - w) // 2, 51), t, font=f, fill=0)
    return im

def screen_menu():
    im, d, f = new_screen()
    d.text((4, 1), "Blivzy AI", font=f, fill=0)
    items = ["Ask anything", "History", "What can I ask?", "Fun fact", "Language: English"]
    for i, t in enumerate(items):
        y = 12 + i * 10
        if i == 0:
            d.rounded_rectangle([0, y, 122, y + 9], radius=2, fill=0)
            d.text((6, y), t, font=f, fill=1)
        else:
            d.text((6, y), t, font=f, fill=0)
    d.rectangle([125, 12, 126, 30], fill=0)
    return im

LAYERS = [("1234567890", "qwertyuiop", "asdfghjkl<", "zxcvbnm#_>"),
          ("1234567890", "+-*/^()=.,", "%!?:'x$&@<", "e;[]{}|#_>")]

def screen_kbd(layer, typed, sug, cur):
    im, d, f = new_screen()
    for i, t in enumerate(sug):
        x = i * 43
        d.rounded_rectangle([x, 0, x + 41, 10], radius=2, outline=0)
        d.text((x + 3, 1), t, font=f, fill=0)
    d.rectangle([0, 12, 127, 22], outline=0)
    d.text((2, 13), typed + "_", font=f, fill=0)
    d.text((112, 13), "#+" if layer else "ab", font=f, fill=0)
    for r, row in enumerate(LAYERS[layer]):
        for c, ch in enumerate(row):
            x, y = 4 + c * 12, 24 + r * 10
            if (r, c) == cur:
                d.rounded_rectangle([x, y, x + 11, y + 9], radius=2, fill=0)
                d.text((x + 3, y), ch, font=f, fill=1)
            else:
                if ch in "<_>#":
                    d.rounded_rectangle([x, y, x + 11, y + 9], radius=2, outline=0)
                d.text((x + 3, y), ch, font=f, fill=0)
    return im

def device(im, scale=5):
    W, H = 128 * scale, 64 * scale
    bg, ink = (255, 130, 0), (18, 10, 0)
    big = Image.new("RGB", (W, H), bg)
    px = big.load()
    for y in range(64):
        for x in range(128):
            if im.getpixel((x, y)) == 0:
                for dy in range(scale - 1):
                    for dx in range(scale - 1):
                        px[x * scale + dx, y * scale + dy] = ink
    m = 34
    out = Image.new("RGB", (W + 2 * m, H + 2 * m), (30, 30, 34))
    ImageDraw.Draw(out).rounded_rectangle([0, 0, W + 2 * m - 1, H + 2 * m - 1], radius=26, outline=(70, 70, 76), width=4)
    out.paste(big, (m, m))
    return out

# Real output strings produced by the app engine (verified on a host test build)
SHOTS = [
    ("splash", lambda: screen_splash()),
    ("menu", lambda: screen_menu()),
    ("keyboard", lambda: screen_kbd(0, "how do i ", ["solve a", "write an", "cook ri"], (1, 4))),
    ("symbols", lambda: screen_kbd(1, "(25+5)*2^3", [], (3, 7))),
    ("math", lambda: screen_text("what is 15% of 80\n\n= 12\n\n(saved as ans)")),
    ("solve", lambda: screen_text("x^2-5x+6 = 0\n\nx1 = 2\nx2 = 3\n\n(numeric search, range -200..200)")),
    ("convert", lambda: screen_text("100 f\n\n= 37.77777778 c")),
    ("answer", lambda: screen_text("YOU: why is the sky blue\n\nBLIVZY AI:\nThe sky looks blue because air scatters short (blue) wavelengths of sunlight more than long ones.")),
    ("numbers", lambda: screen_text("4 numbers\nSum = 43\nMean = 10.75\nMedian = 11.5\nMin = 4\nMax = 16\nRange = 12")),
    ("essay", lambda: screen_text("ESSAY: space\n\n[1] Introduction\nFew subjects are as worth exploring as space. In this essay I will explain what it is, why it matters...")),
]

if __name__ == "__main__":
    os.makedirs(DOCS, exist_ok=True)
    lg = logo(); write_header(lg); icon()
    imgs = []
    for name, fn in SHOTS:
        dv = device(fn()); dv.save(os.path.join(DOCS, "preview_%s.png" % name)); imgs.append(dv)
    w, h = imgs[0].size
    rows = (len(imgs) + 1) // 2
    sheet = Image.new("RGB", (w * 2, h * rows), (18, 18, 22))
    for i, dv in enumerate(imgs):
        sheet.paste(dv, ((i % 2) * w, (i // 2) * h))
    sheet = sheet.resize((w, int(h * rows / 2)))
    sheet.save(os.path.join(DOCS, "preview_sheet.png"))
    device(screen_splash(), 8).save(os.path.join(DOCS, "logo_blivzy_ai.png"))
    print("assets ok")
